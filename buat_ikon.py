"""Generates ikon.ico (exe icon) and ikon_data.py (window icon) without extra libraries.
Run once: python buat_ikon.py   (only needed if you want to change the icon)"""
import base64
import math
import struct
import zlib
from pathlib import Path

HERE = Path(__file__).parent


def lerp(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def in_round_rect(x, y, x0, y0, x1, y1, r):
    cx = min(max(x, x0 + r), x1 - r)
    cy = min(max(y, y0 + r), y1 - r)
    return x0 <= x <= x1 and y0 <= y <= y1 and (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def in_poly(x, y, pts):
    inside = False
    j = len(pts) - 1
    for i in range(len(pts)):
        xi, yi = pts[i]
        xj, yj = pts[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def dist_seg(x, y, a, b):
    ax, ay = a
    bx, by = b
    dx, dy = bx - ax, by - ay
    t = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - (ax + t * dx), y - (ay + t * dy))


def shade(x, y):
    """Colour at design coordinates (0..256); returns (r, g, b, a) 0..255."""
    # rounded blue square with vertical gradient
    if not in_round_rect(x, y, 6, 6, 250, 250, 56):
        return (0, 0, 0, 0)
    c = lerp((59, 130, 246), (29, 78, 216), y / 256)
    # white photo card
    if in_round_rect(x, y, 44, 52, 212, 188, 16):
        c = (255, 255, 255)
        if (x - 88) ** 2 + (y - 92) ** 2 <= 15 ** 2:                       # sun
            c = (147, 197, 253)
        elif in_poly(x, y, [(58, 176), (112, 112), (150, 156), (172, 128), (200, 176)]):  # mountains
            c = (37, 99, 235)
    # green check badge with white ring
    d = math.hypot(x - 188, y - 188)
    if d <= 50:
        c = (255, 255, 255)
    if d <= 42:
        c = (22, 163, 74)
        w = min(dist_seg(x, y, (169, 189), (183, 203)), dist_seg(x, y, (183, 203), (209, 173)))
        if w <= 6:
            c = (255, 255, 255)
    return c + (255,)


def render(size, ss=3):
    rows = []
    for py in range(size):
        row = bytearray()
        for px in range(size):
            acc = [0.0, 0.0, 0.0, 0.0]
            for sy in range(ss):
                for sx in range(ss):
                    x = (px + (sx + .5) / ss) * 256 / size
                    y = (py + (sy + .5) / ss) * 256 / size
                    r, g, b, a = shade(x, y)
                    acc[0] += r * a
                    acc[1] += g * a
                    acc[2] += b * a
                    acc[3] += a
            n = ss * ss
            a = acc[3] / n
            if acc[3] > 0:
                row += bytes((round(acc[0] / acc[3]), round(acc[1] / acc[3]), round(acc[2] / acc[3]), round(a)))
            else:
                row += b"\0\0\0\0"
        rows.append(bytes(row))
    return rows


def png(size):
    raw = b"".join(b"\0" + r for r in render(size))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


sizes = [16, 24, 32, 48, 64, 128, 256]
images = [(s, png(s)) for s in sizes]
head = struct.pack("<HHH", 0, 1, len(images))
offset = 6 + 16 * len(images)
entries, blobs = b"", b""
for s, data in images:
    entries += struct.pack("<BBBBHHII", 0 if s == 256 else s, 0 if s == 256 else s, 0, 0, 1, 32, len(data), offset)
    blobs += data
    offset += len(data)
(HERE / "ikon.ico").write_bytes(head + entries + blobs)
(HERE / "ikon_preview.png").write_bytes(dict(images)[256])
(HERE / "ikon_data.py").write_text(
    '"""Window icon (64px PNG, base64). Generated by buat_ikon.py."""\n'
    f'ICON_PNG_B64 = "{base64.b64encode(dict(images)[64]).decode()}"\n', encoding="utf-8")
print("ikon.ico", (HERE / "ikon.ico").stat().st_size, "bytes | ikon_data.py", (HERE / "ikon_data.py").stat().st_size, "bytes")
